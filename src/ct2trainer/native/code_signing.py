"""Optional code signing for the frozen and generated trainer executables.

Field finding (2026-11-14): a trainer generated by the portable converter was
blocked by Smart App Control (Windows Security).  Smart App Control refuses
unsigned binaries by their binary hash, offers no per-application allow
option, and on Windows 11 turning it off is a one-way switch.  The durable
remedy is an Authenticode signature from a code-signing certificate issued
by a trusted public CA (OV or EV); a self-signed certificate does not clear
Smart App Control.

This module wires that optional signing step into the build
(``tools/native_build.py``) and into trainer generation
(``bundle.build_trainer``):

- configuration is environment-only and is never persisted:
  ``CT2TRAINER_SIGN_PFX`` (path of the PFX certificate store file),
  ``CT2TRAINER_SIGN_PFX_PASSWORD`` (PFX password),
  ``CT2TRAINER_SIGNTOOL`` (explicit ``signtool.exe`` location) and
  ``CT2TRAINER_SIGN_TIMESTAMP_URL`` (timestamp server);
- without ``CT2TRAINER_SIGN_PFX`` nothing is signed and the produced bytes
  are identical to the unsigned flow;
- with it set, a signing failure refuses the build / the trainer generation
  fail-closed (a configured signing that fails never ships an unsigned
  binary), with the named :class:`SigningRefusal` codes
  ``sign-not-win32``, ``sign-signtool-unavailable``,
  ``sign-certificate-missing``, ``sign-failed`` and
  ``sign-verification-failed``;
- after a reported signtool success the certificate table of the PE is
  re-proven by the pure :func:`certificate_table` walk (WIN_CERTIFICATE
  revision 0x0200, certificate type 0x0001).
"""
from __future__ import annotations

import os
from pathlib import Path
import struct
import subprocess
import sys

SIGN_ENV_PFX = "CT2TRAINER_SIGN_PFX"
SIGN_ENV_PFX_PASSWORD = "CT2TRAINER_SIGN_PFX_PASSWORD"
SIGN_ENV_SIGNTOOL = "CT2TRAINER_SIGNTOOL"
SIGN_ENV_TIMESTAMP_URL = "CT2TRAINER_SIGN_TIMESTAMP_URL"
DEFAULT_TIMESTAMP_URL = "http://timestamp.digicert.com"
SIGN_TIMEOUT_SECONDS = 300
_SDK_BIN_ROOTS = (r"C:\Program Files (x86)\Windows Kits\10\bin",
                  r"C:\Program Files\Windows Kits\10\bin")


class SigningRefusal(Exception):
    """Named fail-closed refusal of the optional code-signing step.

    ``code`` is the stable named condition (one of ``sign-not-win32``,
    ``sign-signtool-unavailable``, ``sign-certificate-missing``,
    ``sign-failed``, ``sign-verification-failed``); ``detail`` is the
    displayable evidence.  The message is ``"<code>: <detail>"``.
    """

    def __init__(self, code: str, detail: str):
        super().__init__("%s: %s" % (code, detail))
        self.code = code
        self.detail = detail


def resolve_signing_config(env=None) -> dict | None:
    """Read the optional signing configuration from the environment.

    Pure: never writes, never persists, no side effects.  Returns ``None``
    when ``CT2TRAINER_SIGN_PFX`` is unset or blank (the unsigned default
    flow); otherwise the config mapping with ``pfx_path`` (string),
    ``pfx_password`` (string or None), ``signtool_path`` (string or None,
    meaning "discover under the Windows SDK bin roots") and
    ``timestamp_url`` (string, the documented default when unset).
    """
    env = os.environ if env is None else env
    pfx = (env.get(SIGN_ENV_PFX) or "").strip()
    if not pfx:
        return None
    password = (env.get(SIGN_ENV_PFX_PASSWORD) or "").strip()
    signtool = (env.get(SIGN_ENV_SIGNTOOL) or "").strip()
    timestamp = (env.get(SIGN_ENV_TIMESTAMP_URL) or "").strip()
    return {
        "pfx_path": pfx,
        "pfx_password": password or None,
        "signtool_path": signtool or None,
        "timestamp_url": timestamp or DEFAULT_TIMESTAMP_URL,
    }


def _sdk_version_key(name: str) -> tuple | None:
    """Numeric sort key for a Windows SDK version directory name, or None."""
    parts = []
    for piece in name.split("."):
        if piece.isdigit():
            parts.append(int(piece))
        else:
            break
    return tuple(parts) if parts else None


def find_signtool(roots=None) -> Path | None:
    """Locate ``signtool.exe`` under the Windows SDK bin roots.

    Returns the ``x64\\signtool.exe`` of the numerically highest version
    directory, or None when no root contains it.  ``roots`` is injectable
    for tests (defaults to the two documented SDK bin roots).
    """
    roots = _SDK_BIN_ROOTS if roots is None else roots
    best = None
    for root in roots:
        base = Path(root)
        if not base.is_dir():
            continue
        try:
            entries = list(base.iterdir())
        except OSError:
            continue
        for version_dir in entries:
            if not version_dir.is_dir():
                continue
            key = _sdk_version_key(version_dir.name)
            if key is None:
                continue
            candidate = version_dir / "x64" / "signtool.exe"
            if not candidate.is_file():
                continue
            if best is None or key > best[0]:
                best = (key, candidate)
    return best[1] if best is not None else None


def sign_command(config: dict, path) -> list[str]:
    """Build the signtool sign argv for one executable.  Pure.

    ``signtool sign /v /f <pfx> [/p <pwd>] /fd SHA256 [/tr <url> /td SHA256]
    <path>`` - the documented flags for an Authenticode SHA-256 signature
    with RFC-3161 timestamping.
    """
    argv = [config["signtool_path"], "sign", "/v",
            "/f", str(config["pfx_path"]),
            "/fd", "SHA256"]
    if config.get("pfx_password"):
        argv += ["/p", config["pfx_password"]]
    if config.get("timestamp_url"):
        argv += ["/tr", config["timestamp_url"], "/td", "SHA256"]
    argv.append(str(path))
    return argv


def _output_tail(text, limit: int = 500) -> str:
    text = (text or "").strip()
    if len(text) > limit:
        text = "..." + text[-limit:]
    return text


def _subprocess_run(argv) -> subprocess.CompletedProcess:
    return subprocess.run(list(argv), stdout=subprocess.PIPE,
                          stderr=subprocess.STDOUT, text=True,
                          check=False, timeout=SIGN_TIMEOUT_SECONDS)


def sign_executable(path, config: dict, run=None) -> dict:
    """Sign one PE executable in place through signtool.

    Fail-closed: every failure raises :class:`SigningRefusal` with a named
    code.  ``run`` is the injectable test seam - a callable mapping the
    argv to a result object with ``returncode`` / ``stdout`` (defaults to
    the bounded ``subprocess.run`` wrapper).  Returns the fact mapping
    ``{"signtool": <path>, "evidence": <bounded /v output tail>}``.
    """
    if sys.platform != "win32":
        raise SigningRefusal(
            "sign-not-win32",
            "signtool signing requires Windows (platform is %s)" % sys.platform)
    signtool = config.get("signtool_path") or find_signtool()
    if not signtool or not Path(signtool).is_file():
        if config.get("signtool_path"):
            detail = "configured signtool %s does not exist" % signtool
        else:
            detail = "signtool.exe not found under the Windows SDK bin roots; set %s to its full path" % SIGN_ENV_SIGNTOOL
        raise SigningRefusal("sign-signtool-unavailable", detail)
    pfx = Path(config["pfx_path"])
    if not pfx.is_file():
        raise SigningRefusal("sign-certificate-missing",
                             "certificate store file %s does not exist" % pfx)
    argv = sign_command({"signtool_path": signtool, **config}, path)
    runner = _subprocess_run if run is None else run
    try:
        result = runner(argv)
    except subprocess.TimeoutExpired:
        raise SigningRefusal("sign-failed",
                             "signtool did not finish within %d s" % SIGN_TIMEOUT_SECONDS)
    except OSError as exc:
        raise SigningRefusal("sign-failed", "signtool could not be started: %s" % exc)
    if result.returncode != 0:
        tail = _output_tail(getattr(result, "stderr", "") or getattr(result, "stdout", ""))
        raise SigningRefusal("sign-failed", "signtool exited %d: %s" % (result.returncode, tail))
    return {"signtool": str(signtool), "evidence": _output_tail(getattr(result, "stdout", ""))}


def certificate_table(data: bytes) -> dict:
    """Pure PE security-directory walk over raw file bytes.

    Returns ``{"signed": False}`` for a PE without a security data
    directory (and for bytes that are not a PE at all), and
    ``{"signed": True, "certificate_offset": int, "certificate_length":
    int}`` for a well-formed WIN_CERTIFICATE (revision 0x0200, certificate
    type 0x0001, declared length equal to the security directory size).
    Raises :class:`SigningRefusal` (``sign-verification-failed``) when a
    security directory exists but its certificate table is malformed or
    out of bounds - the named condition a signed file must never carry.
    """
    if len(data) < 64 or data[:2] != b"MZ":
        return {"signed": False}
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    if pe + 24 > len(data) or data[pe:pe + 4] != b"PE\0\0":
        return {"signed": False}
    machine, sections = struct.unpack_from("<HH", data, pe + 4)
    optional_size = struct.unpack_from("<H", data, pe + 20)[0]
    optional = pe + 24
    if sections < 1 or optional + optional_size > len(data):
        return {"signed": False}
    magic = struct.unpack_from("<H", data, optional)[0]
    if magic not in (0x10B, 0x20B):
        return {"signed": False}
    base = 112 if magic == 0x20B else 96
    if optional + base + 40 > len(data):
        return {"signed": False}
    directories = struct.unpack_from("<I", data, optional + base - 4)[0]
    if directories < 5:
        return {"signed": False}
    rva, size = struct.unpack_from("<II", data, optional + base + 32)
    if size == 0:
        return {"signed": False}
    table = optional + optional_size
    if table + 40 * sections > len(data):
        return {"signed": False}
    offset = None
    for index in range(sections):
        entry = table + 40 * index
        virtual_size = struct.unpack_from("<I", data, entry + 8)[0]
        virtual_address = struct.unpack_from("<I", data, entry + 12)[0]
        raw_size = struct.unpack_from("<I", data, entry + 16)[0]
        raw_pointer = struct.unpack_from("<I", data, entry + 20)[0]
        span = max(virtual_size, raw_size)
        if virtual_address <= rva < virtual_address + span:
            offset = raw_pointer + (rva - virtual_address)
            break
    if offset is None:
        raise SigningRefusal("sign-verification-failed",
                             "certificate RVA 0x%X does not map into a section" % rva)
    if offset + 8 > len(data) or size > len(data) - offset:
        raise SigningRefusal("sign-verification-failed",
                             "certificate table is truncated (declared %d bytes)" % size)
    declared = struct.unpack_from("<I", data, offset)[0]
    if declared < 8 or size > len(data) - offset or declared != size:
        raise SigningRefusal("sign-verification-failed",
                             "certificate table length mismatch (declared %d, directory %d)" % (declared, size))
    revision, certificate_type = struct.unpack_from("<HH", data, offset + 4)
    if revision != 0x0200:
        raise SigningRefusal("sign-verification-failed",
                             "unexpected certificate revision 0x%04X (want 0x0200)" % revision)
    if certificate_type != 0x0001:
        raise SigningRefusal("sign-verification-failed",
                             "unexpected certificate type 0x%04X (want 0x0001, PKCS#7)" % certificate_type)
    return {"signed": True, "certificate_offset": offset, "certificate_length": declared}


def sign_and_verify(path, config: dict, run=None) -> dict:
    """Sign one PE executable in place and prove the certificate afterwards.

    Fail-closed: every failure raises :class:`SigningRefusal` with a named
    code, so a caller that configured signing must never ship an unsigned
    binary.  Returns the fact mapping ``{"signed": True, "signtool": ...,
    "evidence": ..., "certificate": {...}}`` (JSON-serializable for build
    reports).
    """
    path = Path(path)
    facts = sign_executable(path, config, run=run)
    walk = certificate_table(path.read_bytes())
    if not walk.get("signed"):
        raise SigningRefusal("sign-verification-failed",
                             "signtool reported success but no certificate table is present in %s" % path.name)
    return {"signed": True, **facts, "certificate": walk}


def sign_if_configured(path, env=None, run=None) -> dict:
    """Sign ``path`` when the signing environment is configured; no-op
    otherwise.  The returned fact mapping is JSON-serializable for build
    reports: ``{"signed": False, "reason": "not-configured"}`` or the
    signed facts.  A configured signing that fails raises
    :class:`SigningRefusal` (fail-closed, never a silent unsigned ship).
    """
    config = resolve_signing_config(env)
    if config is None:
        return {"signed": False, "reason": "not-configured"}
    return sign_and_verify(path, config, run=run)
