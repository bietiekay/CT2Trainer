"""Optional code signing (Smart App Control handling).

Field finding 2026-11-14: a trainer generated by the portable converter
was blocked by Smart App Control (Windows Security).  SAC blocks unsigned
binaries by their binary hash, offers no per-app allow, and is a one-way
off switch on Windows 11 - the durable fix is an Authenticode signature
from a trusted-CA code-signing certificate.  ``code_signing`` wires that
optional step into the build (``tools/native_build.py``) and the trainer
generation (``bundle.build_trainer``): environment-only configuration
(never persisted), byte-identical unsigned flow without
``CT2TRAINER_SIGN_PFX``, and fail-closed named refusals when a configured
signing fails.
"""
from __future__ import annotations

import struct
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path
from types import SimpleNamespace
from unittest import mock

from ct2trainer.native import code_signing
from ct2trainer.native.code_signing import (
    DEFAULT_TIMESTAMP_URL,
    SIGN_ENV_PFX,
    SIGN_ENV_PFX_PASSWORD,
    SIGN_ENV_SIGNTOOL,
    SIGN_ENV_TIMESTAMP_URL,
    certificate_table,
    find_signtool,
    resolve_signing_config,
    sign_and_verify,
    sign_command,
    sign_executable,
    sign_if_configured,
    SigningRefusal,
)


def _make_sdk_root(root: Path, versions, with_signtool=True):
    """Build a fake Windows SDK bin root with the given version dirs."""
    for name in versions:
        arch = root / name / "x64"
        arch.mkdir(parents=True)
        if with_signtool:
            (arch / "signtool.exe").write_bytes(b"fake")
        (root / name / "x86").mkdir()


class SigningConfigTests(unittest.TestCase):
    def test_unset_environment_is_the_unsigned_default(self):
        self.assertIsNone(resolve_signing_config({}))
        with mock.patch.dict("os.environ", {}, clear=True):
            self.assertIsNone(resolve_signing_config())

    def test_whitespace_pfx_is_unset(self):
        self.assertIsNone(resolve_signing_config({SIGN_ENV_PFX: "   "}))

    def test_pfx_only_gets_the_documented_defaults(self):
        config = resolve_signing_config({SIGN_ENV_PFX: "C:\\certs\\mine.pfx"})
        self.assertEqual(config["pfx_path"], "C:\\certs\\mine.pfx")
        self.assertIsNone(config["pfx_password"])
        self.assertIsNone(config["signtool_path"])
        self.assertEqual(config["timestamp_url"], DEFAULT_TIMESTAMP_URL)

    def test_full_configuration_is_read_verbatim(self):
        config = resolve_signing_config({
            SIGN_ENV_PFX: " C:\\certs\\mine.pfx ",
            SIGN_ENV_PFX_PASSWORD: "secret",
            SIGN_ENV_SIGNTOOL: "C:\\kits\\signtool.exe",
            SIGN_ENV_TIMESTAMP_URL: "http://ts.example.com",
        })
        self.assertEqual(config["pfx_path"], "C:\\certs\\mine.pfx")
        self.assertEqual(config["pfx_password"], "secret")
        self.assertEqual(config["signtool_path"], "C:\\kits\\signtool.exe")
        self.assertEqual(config["timestamp_url"], "http://ts.example.com")


class SigningRefusalTests(unittest.TestCase):
    def test_message_carries_code_and_detail(self):
        refusal = SigningRefusal("sign-failed", "signtool exited 1")
        self.assertEqual(refusal.code, "sign-failed")
        self.assertEqual(refusal.detail, "signtool exited 1")
        self.assertEqual(str(refusal), "sign-failed: signtool exited 1")
        self.assertIsInstance(refusal, Exception)


class SigntoolDiscoveryTests(unittest.TestCase):
    def test_highest_version_dir_wins(self):
        with tempfile.TemporaryDirectory() as name:
            root = Path(name)
            _make_sdk_root(root, ("10.0.19041.0", "10.0.26100.0"))
            found = find_signtool(roots=[str(root)])
            self.assertEqual(
                found, root / "10.0.26100.0" / "x64" / "signtool.exe")

    def test_only_32bit_layout_is_not_found(self):
        with tempfile.TemporaryDirectory() as name:
            root = Path(name)
            version = root / "10.0.26100.0" / "x86"
            version.mkdir(parents=True)
            (version / "signtool.exe").write_bytes(b"fake")
            self.assertIsNone(find_signtool(roots=[str(root)]))

    def test_nonexistent_and_empty_roots_are_none(self):
        self.assertIsNone(find_signtool(roots=[r"C:\no-such-root"]))
        with tempfile.TemporaryDirectory() as name:
            self.assertIsNone(find_signtool(roots=[name]))

    def test_non_numeric_version_dirs_are_skipped(self):
        with tempfile.TemporaryDirectory() as name:
            root = Path(name)
            _make_sdk_root(root, ("junk", "10.0.19041.0"))
            found = find_signtool(roots=[str(root)])
            self.assertEqual(found, root / "10.0.19041.0" / "x64" / "signtool.exe")


class SignCommandTests(unittest.TestCase):
    def test_base_argv_without_password(self):
        argv = sign_command({"signtool_path": "signtool.exe",
                             "pfx_path": "cert.pfx", "pfx_password": None,
                             "timestamp_url": "http://ts.example.com"},
                            "trainer.exe")
        self.assertEqual(argv, ["signtool.exe", "sign", "/v", "/f", "cert.pfx",
                                "/fd", "SHA256", "/tr", "http://ts.example.com",
                                "/td", "SHA256", "trainer.exe"])

    def test_password_joins_between_file_and_digest(self):
        argv = sign_command({"signtool_path": "signtool.exe",
                             "pfx_path": "cert.pfx", "pfx_password": "pw",
                             "timestamp_url": DEFAULT_TIMESTAMP_URL},
                            "out\\trainer.exe")
        self.assertEqual(argv, ["signtool.exe", "sign", "/v", "/f", "cert.pfx",
                                "/fd", "SHA256", "/p", "pw",
                                "/tr", DEFAULT_TIMESTAMP_URL, "/td", "SHA256",
                                "out\\trainer.exe"])


class _Recorder:
    def __init__(self, result):
        self.result = result
        self.argv = None

    def __call__(self, argv):
        self.argv = list(argv)
        return self.result


class SignExecutableTests(unittest.TestCase):
    def _config(self, directory, signtool=True, pfx=True):
        signtool_path = directory / "signtool.exe"
        if signtool is not False:
            signtool_path.write_bytes(b"fake")
        pfx_path = directory / "cert.pfx"
        if pfx:
            pfx_path.write_bytes(b"fake-pfx")
        return {"pfx_path": str(pfx_path), "pfx_password": None,
                "signtool_path": str(signtool_path) if signtool is not False else str(directory / "absent.exe"),
                "timestamp_url": "http://ts.example.com"}

    def test_platform_guard_refuses_non_windows(self):
        with tempfile.TemporaryDirectory() as name:
            config = self._config(Path(name))
            with mock.patch.object(code_signing.sys, "platform", "linux"):
                with self.assertRaisesRegex(SigningRefusal, r"sign-not-win32"):
                    sign_executable(Path(name) / "x.exe", config)

    def test_missing_configured_signtool_is_named(self):
        with tempfile.TemporaryDirectory() as name:
            config = self._config(Path(name), signtool=False)
            with self.assertRaisesRegex(SigningRefusal, r"sign-signtool-unavailable"):
                sign_executable(Path(name) / "x.exe", config)

    def test_missing_discovered_signtool_is_named(self):
        with tempfile.TemporaryDirectory() as name:
            config = self._config(Path(name))
            config["signtool_path"] = None
            with mock.patch.object(code_signing, "find_signtool", return_value=None):
                with self.assertRaisesRegex(SigningRefusal, r"sign-signtool-unavailable"):
                    sign_executable(Path(name) / "x.exe", config)

    def test_missing_pfx_is_named(self):
        with tempfile.TemporaryDirectory() as name:
            config = self._config(Path(name), pfx=False)
            with self.assertRaisesRegex(SigningRefusal, r"sign-certificate-missing"):
                sign_executable(Path(name) / "x.exe", config)

    def test_nonzero_exit_is_sign_failed_with_evidence(self):
        with tempfile.TemporaryDirectory() as name:
            target = Path(name) / "x.exe"
            target.write_bytes(b"MZ" + b"\x00" * 64)
            config = self._config(Path(name))
            recorder = _Recorder(SimpleNamespace(returncode=1, stdout="",
                                                 stderr="signing error: cert expired"))
            with self.assertRaises(SigningRefusal) as caught:
                sign_executable(target, config, run=recorder)
            self.assertEqual(caught.exception.code, "sign-failed")
            self.assertIn("exited 1", caught.exception.detail)
            self.assertIn("cert expired", caught.exception.detail)

    def test_runner_oserror_is_sign_failed(self):
        with tempfile.TemporaryDirectory() as name:
            config = self._config(Path(name))

            def boom(argv):
                raise OSError("refused")
            with self.assertRaisesRegex(SigningRefusal, r"sign-failed: signtool could not be started"):
                sign_executable(Path(name) / "x.exe", config, run=boom)

    def test_timeout_is_sign_failed(self):
        with tempfile.TemporaryDirectory() as name:
            config = self._config(Path(name))

            def boom(argv):
                raise subprocess.TimeoutExpired("signtool", 300)
            with self.assertRaisesRegex(SigningRefusal, r"sign-failed: signtool did not finish"):
                sign_executable(Path(name) / "x.exe", config, run=boom)

    def test_success_returns_evidence_and_exact_argv(self):
        with tempfile.TemporaryDirectory() as name:
            target = Path(name) / "x.exe"
            target.write_bytes(b"MZ" + b"\x00" * 64)
            config = self._config(Path(name))
            config["pfx_password"] = "pw"
            recorder = _Recorder(SimpleNamespace(returncode=0,
                                                 stdout="Successfully signed \"x.exe\".\r\n"
                                                        "Number of files processed: 1",
                                                 stderr=""))
            facts = sign_executable(target, config, run=recorder)
            self.assertEqual(facts["signtool"], config["signtool_path"])
            self.assertIn("Successfully signed", facts["evidence"])
            expected = [config["signtool_path"], "sign", "/v", "/f",
                        config["pfx_path"], "/fd", "SHA256",
                        "/p", "pw", "/tr", "http://ts.example.com", "/td",
                        "SHA256", str(target)]
            self.assertEqual(recorder.argv, expected)


def make_pe(with_certificate=None, cert_rva=None, cert_directory_size=None,
            cert_revision=0x0200, cert_type=0x0001, declared_length=None):
    """Assemble a minimal x64 PE file with one section.

    ``with_certificate`` is the raw WIN_CERTIFICATE blob placed inside the
    section (None = no security data directory, an ordinary unsigned PE).
    The declared WIN_CERTIFICATE dwLength can be decoupled from the
    security directory size to exercise the length-mismatch refusal.
    """
    dos = bytearray(64)
    dos[:2] = b"MZ"
    struct.pack_into("<I", dos, 0x3C, 64)
    coff = bytearray(24)
    coff[0:4] = b"PE\0\0"
    struct.pack_into("<H", coff, 4, 0x8664)
    struct.pack_into("<H", coff, 6, 1)
    struct.pack_into("<H", coff, 20, 240)
    struct.pack_into("<H", coff, 22, 0x22)
    optional = bytearray(240)
    struct.pack_into("<H", optional, 0, 0x20B)
    struct.pack_into("<Q", optional, 24, 0x140000000)
    struct.pack_into("<I", optional, 32, 0x1000)
    struct.pack_into("<I", optional, 36, 0x200)
    struct.pack_into("<I", optional, 56, 0x2000)
    struct.pack_into("<I", optional, 60, 368)
    struct.pack_into("<H", optional, 68, 9)
    struct.pack_into("<H", optional, 70, 0x16)
    struct.pack_into("<I", optional, 108, 16)
    body = bytearray(0x200)
    section = bytearray(40)
    section[0:8] = b".text\0\0\0"
    struct.pack_into("<I", section, 8, 0x1000)
    struct.pack_into("<I", section, 12, 0x1000)
    struct.pack_into("<I", section, 16, 0x200)
    struct.pack_into("<I", section, 20, 368)
    struct.pack_into("<I", section, 36, 0x60000020)
    if with_certificate is not None:
        body[0x100:0x100 + len(with_certificate)] = with_certificate
        struct.pack_into("<II", optional, 112 + 32,
                         cert_rva if cert_rva is not None else 0x1100,
                         cert_directory_size if cert_directory_size is not None
                         else len(with_certificate))
    return bytes(dos + coff + optional + section + body)


def make_cert(der_length=64, revision=0x0200, cert_type=0x0001,
              declared_length=None):
    blob = bytearray(8 + der_length)
    struct.pack_into("<IHH", blob, 0,
                     declared_length if declared_length is not None else 8 + der_length,
                     revision, cert_type)
    blob[8:] = b"\x30" * der_length
    return bytes(blob)


class CertificateTableTests(unittest.TestCase):
    def test_non_pe_bytes_are_unsigned(self):
        self.assertEqual(certificate_table(b"JUNK" * 32), {"signed": False})
        self.assertEqual(certificate_table(b"MZ"), {"signed": False})

    def test_pe_without_security_directory_is_unsigned(self):
        self.assertEqual(certificate_table(make_pe()), {"signed": False})

    def test_wellformed_certificate_is_proved(self):
        facts = certificate_table(make_pe(with_certificate=make_cert()))
        self.assertTrue(facts["signed"])
        self.assertEqual(facts["certificate_offset"], 368 + 0x100)
        self.assertEqual(facts["certificate_length"], 72)

    def test_unmapped_rva_is_named_refusal(self):
        with self.assertRaisesRegex(SigningRefusal, r"sign-verification-failed"):
            certificate_table(make_pe(with_certificate=make_cert(),
                                      cert_rva=0x9000))

    def test_truncated_certificate_is_named_refusal(self):
        with self.assertRaisesRegex(SigningRefusal, r"sign-verification-failed"):
            certificate_table(make_pe(with_certificate=make_cert(),
                                      cert_directory_size=800))

    def test_declared_length_mismatch_is_named_refusal(self):
        with self.assertRaisesRegex(SigningRefusal, r"sign-verification-failed"):
            certificate_table(make_pe(with_certificate=make_cert(
                declared_length=80), cert_directory_size=72))

    def test_wrong_revision_is_named_refusal(self):
        with self.assertRaisesRegex(SigningRefusal, r"sign-verification-failed"):
            certificate_table(make_pe(with_certificate=make_cert(revision=0x0100)))

    def test_wrong_certificate_type_is_named_refusal(self):
        with self.assertRaisesRegex(SigningRefusal, r"sign-verification-failed"):
            certificate_table(make_pe(with_certificate=make_cert(cert_type=0x0002)))


class SignIfConfiguredTests(unittest.TestCase):
    def _signed_pe(self):
        return make_pe(with_certificate=make_cert())

    def test_not_configured_is_a_noop_fact(self):
        with tempfile.TemporaryDirectory() as name:
            target = Path(name) / "x.exe"
            target.write_bytes(b"MZ" + b"\x00" * 64)
            facts = sign_if_configured(target, env={})
            self.assertEqual(facts, {"signed": False, "reason": "not-configured"})
            self.assertEqual(target.read_bytes(), b"MZ" + b"\x00" * 64)

    def test_configured_success_signs_and_proves(self):
        with tempfile.TemporaryDirectory() as name:
            target = Path(name) / "x.exe"
            target.write_bytes(b"MZ" + b"\x00" * 64)
            signtool_path = Path(name) / "signtool.exe"
            signtool_path.write_bytes(b"fake")
            pfx = Path(name) / "cert.pfx"
            pfx.write_bytes(b"fake-pfx")
            env = {SIGN_ENV_PFX: str(pfx), SIGN_ENV_SIGNTOOL: str(signtool_path)}

            def fake_run(argv):
                Path(argv[-1]).write_bytes(self._signed_pe())
                return SimpleNamespace(returncode=0, stdout="ok", stderr="")

            facts = sign_if_configured(target, env=env, run=fake_run)
            self.assertTrue(facts["signed"])
            self.assertEqual(facts["certificate"]["certificate_length"], 72)
            self.assertEqual(certificate_table(target.read_bytes())["signed"], True)

    def test_configured_failure_refuses_fail_closed(self):
        with tempfile.TemporaryDirectory() as name:
            target = Path(name) / "x.exe"
            target.write_bytes(b"MZ" + b"\x00" * 64)
            signtool_path = Path(name) / "signtool.exe"
            signtool_path.write_bytes(b"fake")
            pfx = Path(name) / "cert.pfx"
            pfx.write_bytes(b"fake-pfx")
            env = {SIGN_ENV_PFX: str(pfx), SIGN_ENV_SIGNTOOL: str(signtool_path)}
            with self.assertRaisesRegex(SigningRefusal, r"sign-failed"):
                sign_if_configured(target, env=env,
                                   run=lambda argv: SimpleNamespace(
                                       returncode=1, stdout="", stderr="boom"))

    def test_signtool_success_without_certificate_table_refuses(self):
        with tempfile.TemporaryDirectory() as name:
            target = Path(name) / "x.exe"
            target.write_bytes(make_pe())
            signtool_path = Path(name) / "signtool.exe"
            signtool_path.write_bytes(b"fake")
            pfx = Path(name) / "cert.pfx"
            pfx.write_bytes(b"fake-pfx")
            env = {SIGN_ENV_PFX: str(pfx), SIGN_ENV_SIGNTOOL: str(signtool_path)}
            with self.assertRaisesRegex(SigningRefusal, r"sign-verification-failed"):
                sign_if_configured(target, env=env,
                                   run=lambda argv: SimpleNamespace(
                                       returncode=0, stdout="ok", stderr=""))


class SignAndVerifyTests(unittest.TestCase):
    def test_sign_and_verify_needs_a_real_certificate(self):
        with tempfile.TemporaryDirectory() as name:
            config = {"pfx_path": str(Path(name) / "cert.pfx"),
                      "pfx_password": None,
                      "signtool_path": str(Path(name) / "signtool.exe"),
                      "timestamp_url": "http://ts.example.com"}
            (Path(name) / "cert.pfx").write_bytes(b"fake-pfx")
            (Path(name) / "signtool.exe").write_bytes(b"fake")
            target = Path(name) / "x.exe"
            target.write_bytes(make_pe())

            def no_op_run(argv):
                return SimpleNamespace(returncode=0, stdout="ok", stderr="")

            with self.assertRaises(SigningRefusal) as caught:
                sign_and_verify(target, config, run=no_op_run)
            self.assertEqual(caught.exception.code, "sign-verification-failed")


